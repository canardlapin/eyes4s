#!/usr/bin/env python3
"""Generate portable score checks from direct point-kernel sums, without Scala or R."""
import argparse
import json
from pathlib import Path
import sys

from analyze import ROOT, INPUT, identity, source, scores
sys.path.insert(0, str(ROOT / "tools/private-fixtures"))
from end_to_end import axes, gaussian

OUTPUT = ROOT / "plan/src/test/scala/eyes4s/plan/DensityApproximationReference.scala"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(INPUT.read_text())
    items = {identity(item):item for item in data["items"]}
    rows = []
    for nx,sigma in ((8,.2),(16,.8),(32,1.6),(128,.8)):
        p = dict(nx=nx,ny=nx*3//4,sigma_px=sigma,x_min=-1,y_min=-1,x_max=7,y_max=5)
        xs,ys = axes(p)
        maps = {key:gaussian(p,source(item),xs,ys,quantize=True,truncate=True) for key,item in items.items()}
        for key,item in items.items():
            if item["phase"] != "near-midpoint":continue
            controls = [k for k,v in items.items() if v["participant"]==item["participant"] and v["phase"]=="encode" and v["stimulus"]!=item["stimulus"]]
            score = scores(maps,key,controls)
            rows.append(f'    Row({nx}, {sigma}, "{key}", {score["matched"]!r}, {score["control"]!r}, {score["difference"]!r})')
    header = (ROOT / "plan/src/main/scala/eyes4s/plan/StudyPlan.scala").read_text().split("package ")[0]
    result = header + '''package eyes4s.plan

// Generated by tools/density-approximation/generate_regression.py; direct-sum oracle.
// format: off
private[plan] object DensityApproximationReference:
  final case class Row(nx: Int, sigma: Double, id: String, matched: Double, control: Double, difference: Double)
  val rows: Vector[Row] = Vector(
''' + ",\n".join(rows) + "\n  )\n// format: on\n"
    if args.check:
        assert OUTPUT.read_text()==result,"direct-sum regression drift"
    else:
        OUTPUT.write_text(result)


if __name__ == "__main__":
    main()
