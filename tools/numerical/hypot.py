#!/usr/bin/env python3
"""Regenerate/check portable fdlibm hypot cases against the configured JVM StrictMath."""
import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
MASK = (1 << 64) - 1

def cases():
    anchors = [0, 1 << 63, 1, 0x000fffffffffffff, 0x0010000000000000,
               0x0010000000000001, 0x3fe0000000000000, 0x3ff0000000000000,
               0xbff0000000000000, 0x3ff0000000000001, 0x4000000000000000,
               0x4000000000000001, 0x4008000000000000, 0x4010000000000000,
               0x7ff0000000000000, 0xfff0000000000000, 0x7ff8000000000000,
               0x7ff8000000001234, 0x7fefffffffffffff, 0x7feffffffffffffe,
               (1023 + 500) << 52, (1023 + 501) << 52,
               (1023 - 500) << 52, (1023 - 501) << 52]
    values = [(a, b) for a in anchors for b in anchors]
    state = 0x5eed1234abcdef
    def next_word():
        nonlocal state
        state = (state ^ (state << 13)) & MASK
        state ^= state >> 7
        state = (state ^ (state << 17)) & MASK
        return state
    values += [(next_word(), next_word()) for _ in range(256)]
    for i in range(192):
        exponent = ((i * 11) % 2047) << 52
        values.append((exponent | (next_word() & 0x000fffffffffffff),
                       exponent | (next_word() & 0x000fffffffffffff)))
    assert len(values) == 1024
    return values

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    java_home = os.environ.get('JAVA_HOME')
    def binary(name):
        return str(Path(java_home) / 'bin' / name) if java_home else shutil.which(name)
    pairs = cases()
    source = '''import java.io.*;
public final class HypotOracle {
  public static void main(String[] args) throws Exception {
    BufferedReader in = new BufferedReader(new InputStreamReader(System.in));
    for (String line; (line = in.readLine()) != null;) {
      String[] p = line.split(" ");
      double a = Double.longBitsToDouble(Long.parseUnsignedLong(p[0],16));
      double b = Double.longBitsToDouble(Long.parseUnsignedLong(p[1],16));
      System.out.printf(java.util.Locale.ROOT,"%016x%n",Double.doubleToLongBits(StrictMath.hypot(a,b)));
    }
  }
}
'''
    with tempfile.TemporaryDirectory(prefix='eyes4s-hypot-oracle-') as temporary:
        folder = Path(temporary)
        (folder / 'HypotOracle.java').write_text(source)
        subprocess.run([binary('javac'), '-d', temporary, str(folder / 'HypotOracle.java')], check=True)
        text = ''.join(f'{a:016x} {b:016x}\n' for a, b in pairs)
        out = subprocess.run([binary('java'), '-cp', temporary, 'HypotOracle'], input=text,
                             text=True, stdout=subprocess.PIPE, check=True).stdout.splitlines()
    assert len(out) == len(pairs)
    rows = '\n'.join(f'{a:016x} {b:016x} {expected}' for (a, b), expected in zip(pairs, out))
    assert len(rows.encode('utf-8')) < 65535
    header = (ROOT / 'design/src/main/scala/eyes4s/design/LeastSquares.scala').read_text().split('package eyes4s.design')[0]
    data = header + 'package eyes4s.design\n\n// Generated by tools/numerical/hypot.py; do not hand-edit.\n// format: off\nprivate[design] object HypotReference:\n  val records: String = """' + rows + '"""\n// format: on\n'
    target = ROOT / 'design/src/test/scala/eyes4s/design/HypotReference.scala'
    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(data)
    elif not target.exists() or target.read_text() != data:
        raise SystemExit(f'Hypot reference differs: {target}; regenerate with --write and review')
    print('Verified 1024 hypot binary cases; SHA256=' + hashlib.sha256(rows.encode()).hexdigest())

if __name__ == '__main__':
    main()
