# Offline, base-R-only consumer of actual public Scala artifacts. No R oracle in normal tests.
args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==1)
root <- args[[1]]
read <- function(name) read.csv(file.path(root,paste0(name,".csv")),colClasses="character",check.names=FALSE,na.strings=NULL,encoding="UTF-8")
expect <- function(actual,expected,tolerance=1e-12) stopifnot(length(actual)==length(expected),all(abs(as.numeric(actual)-expected)<=tolerance))
pairs <- read("pairs")
stopifnot(nrow(pairs)==9,sum(pairs$status=="failure")==3,all(nchar(pairs$table_sha256)==64),all(grepl(intToUtf8(955),pairs$left_key_json,fixed=TRUE)))
expect(pairs$value[pairs$value__valid=="true"],c(2,3,4,3,4,5))
stopifnot(all(pairs$value[pairs$status=="failure"]==""),all(pairs$value__valid[pairs$status=="failure"]=="false"),all(nchar(pairs$error_json[pairs$status=="failure"])>0))
structured <- read("structured-pairs")
stopifnot(nrow(structured)==45,sum(structured$status=="failure")==15,identical(structured$component[1:5],c("shape","direction","length","position","duration")))
expect(structured$value[1:5],c(.1,.2,.3,.4,.5))
reduced <- read("reductions")
stopifnot(identical(reduced$selected,c("3","3","3")),identical(reduced$contributing,c("3","3","0")))
expect(reduced$value[1:2],c(3,4))
contrasts <- read("contrasts")
stopifnot(nrow(contrasts)==9,all(contrasts$selected__valid[contrasts$role=="difference"]=="false"))
expect(contrasts$value[contrasts$role=="difference" & contrasts$status=="success"],c(0,0))
points <- read("point-pointsamples")
stopifnot(nrow(points)==30,"9007199254740993" %in% points$time_us,"9223372036854775807" %in% points$time_us,sum(points$status=="failure")==12)
bins <- read("point-pointbins")
stopifnot(nrow(bins)==18,sum(bins$includes_final_endpoint=="true")==9)
stopifnot(nrow(read("point-pointcontrols"))==30,nrow(read("point-pointsources"))==3)
expect(read("fixed-templatecoefficients")$coefficient,2)
expect(read("fixed-templatepredictions")$predicted,6)
expect(read("fixed-templatepredictions")$residual,1)
expect(read("learned-templatepredictions")$predicted,1.5)
stopifnot(nrow(read("learned-templateexclusions"))==1)
expect(read("olscoefficients")$value,c(.25,.75))
expect(read("olsdiagnostics")$residual_sum_squares,0)
stopifnot(nrow(read("olscells"))==4,nrow(read("repetition-0"))==6,nrow(read("repetition-1"))==12)
stopifnot(nrow(read("empty-pairs"))==0,nrow(read("study"))==2,nrow(read("temporalcontrasts"))==2,nrow(read("temporalcoverage"))==4)
cat("Base R independently verified exported identities, component order, exact times, failures, counts and analytic values.\n")
