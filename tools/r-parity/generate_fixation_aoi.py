#!/usr/bin/env python3
"""Exact rational rectangle-membership and fixation-duration oracle; no native or R call."""
import argparse
from collections import Counter
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
import parity

ROOT, HERE = parity.ROOT, parity.HERE
INPUT = HERE / "fixtures/cases/cr7-fixation-conformance.json"
OUTPUT = HERE / "fixtures/cr7-fixation-conformance.json"
SCALA = ROOT / "laws/src/test/scala/eyes4s/laws/FixationAoiReference.scala"


def inside(rect, x, y):
    lo_x, lo_y, hi_x, hi_y = map(Fraction, rect)
    return lo_x <= x < hi_x and lo_y <= y < hi_y


def oracle(case):
    areas, fixes, frame = case["areas"], case["fixations"], case["frame"]
    assert fixes and all(f["duration_us"] > 0 for f in fixes)
    assert all(b["onset_us"] >= a["onset_us"] + a["duration_us"] for a, b in zip(fixes, fixes[1:]))
    nx, ny = case["resolution"]
    raster_counts = [sum(
        inside(a["rect"], Fraction((2 * ix + 1) * frame["width"], 2 * nx),
               Fraction((2 * iy + 1) * frame["height"], 2 * ny))
        for ix in range(nx) for iy in range(ny)
    ) for a in areas]
    memberships = []
    for index, fix in enumerate(fixes):
        x, y = Fraction(fix["x"]), Fraction(fix["y"])
        if not 0 <= x < frame["width"] or not 0 <= y < frame["height"]:
            memberships.append({"kind": "offSurface", "ids": []})
            continue
        containing = [i for i, a in enumerate(areas) if inside(a["rect"], x, y)]
        if case["policy"] == "reject" and len(containing) > 1:
            return {"failure": {"fixation_index": index, "areas": [areas[i]["id"] for i in containing]}}
        if case["policy"] == "exclusive":
            containing = containing[:1]
        elif case["policy"] == "smallest" and containing:
            containing = [min(containing, key=lambda i: raster_counts[i])]
        memberships.append({"kind": "areas" if containing else "background", "ids": [areas[i]["id"] for i in containing]})
    union = sum(f["duration_us"] for f, m in zip(fixes, memberships) if m["ids"])
    background = sum(f["duration_us"] for f, m in zip(fixes, memberships) if m["kind"] == "background")
    off_surface = sum(f["duration_us"] for f, m in zip(fixes, memberships) if m["kind"] == "offSurface")
    duplicated = sum(f["duration_us"] * max(0, len(m["ids"]) - 1) for f, m in zip(fixes, memberships))
    extent = fixes[-1]["onset_us"] + fixes[-1]["duration_us"] - fixes[0]["onset_us"]
    gaps = extent - sum(f["duration_us"] for f in fixes)
    assert extent == union + background + off_surface + gaps
    metrics = []
    for area in areas:
        present = [area["id"] in m["ids"] for m in memberships]
        selected = [f for f, hit in zip(fixes, present) if hit]
        dwell = sum(f["duration_us"] for f in selected)
        visits = sum(hit and (i == 0 or not present[i - 1]) for i, hit in enumerate(present))
        ratio = Fraction(dwell, union + background) if union + background else None
        metrics.append({"id": area["id"], "dwell_us": dwell, "proportion": str(ratio) if ratio is not None else None,
                        "first_entry_us": selected[0]["onset_us"] - fixes[0]["onset_us"] if selected else None,
                        "fixation_count": len(selected), "entry_count": visits, "visit_count": visits})
    assert sum(m["dwell_us"] for m in metrics) == union + duplicated
    edges = Counter((a, b) for before, after in zip(memberships, memberships[1:])
                    if before["ids"] != after["ids"] for a in before["ids"] for b in after["ids"] if a != b)
    transitions = [{"from": a["id"], "to": b["id"], "count": edges[(a["id"], b["id"])]}
                   for a in areas for b in areas if edges[(a["id"], b["id"])]]
    return {"memberships": memberships, "metrics": metrics, "transitions": transitions,
            "report": {"union_us": union, "background_us": background, "off_surface_us": off_surface,
                       "inter_fixation_us": gaps, "duplicated_us": duplicated}}


def vec(items):
    return "Vector(" + ",".join(items) + ")"


def option(value, render):
    return "None" if value is None else "Some(" + render(value) + ")"


def scala(cases, expected):
    header = (ROOT / "aoi/src/main/scala/eyes4s/aoi/Aoi.scala").read_text().split("package ")[0]
    result = header + "package eyes4s.laws\n\n// Generated by tools/r-parity/generate_fixation_aoi.py. Do not hand-edit.\n// format: off\nprivate[laws] object FixationAoiReference:\n"
    result += "  final case class Fix(onset: Long, duration: Long, x: Double, y: Double)\n"
    result += "  final case class Area(id: String, label: String, xMin: Double, yMin: Double, xMax: Double, yMax: Double)\n"
    result += "  final case class Metric(id: String, dwell: Long, proportion: Option[Double], firstEntry: Option[Long], fixationCount: Int, entryCount: Int, visitCount: Int)\n"
    result += "  final case class Expected(memberships: Vector[(String,Vector[String])], metrics: Vector[Metric], transitions: Vector[(String,String,Int)], report: Vector[Long])\n"
    result += "  final case class Case(name: String, policy: String, nx: Int, ny: Int, areas: Vector[Area], fixes: Vector[Fix], expected: Option[Expected], overlapIndex: Option[Int], overlapAreas: Vector[String])\n"
    rows = []
    for c, e in zip(cases, expected, strict=True):
        areas = vec("Area(" + json.dumps(a["id"]) + "," + json.dumps(a["label"]) + "," + ",".join(repr(float(v)) for v in a["rect"]) + ")" for a in c["areas"])
        fixes = vec(f'Fix({f["onset_us"]}L,{f["duration_us"]}L,{float(f["x"])!r},{float(f["y"])!r})' for f in c["fixations"])
        if "failure" in e:
            exp, index, overlap = "None", f'Some({e["failure"]["fixation_index"]})', vec(map(json.dumps, e["failure"]["areas"]))
        else:
            members = vec("(" + json.dumps(m["kind"]) + "," + vec(map(json.dumps, m["ids"])) + ")" for m in e["memberships"])
            metrics = vec("Metric(" + json.dumps(m["id"]) + f',{m["dwell_us"]}L,' + option(m["proportion"], lambda r: repr(float(Fraction(r)))) + "," + option(m["first_entry_us"], lambda t: f"{t}L") + f',{m["fixation_count"]},{m["entry_count"]},{m["visit_count"]})' for m in e["metrics"])
            transitions = vec("(" + json.dumps(t["from"]) + "," + json.dumps(t["to"]) + f',{t["count"]})' for t in e["transitions"])
            report = vec(f'{e["report"][k]}L' for k in ["union_us", "background_us", "off_surface_us", "inter_fixation_us", "duplicated_us"])
            exp, index, overlap = "Some(Expected(" + ",".join([members, metrics, transitions, report]) + "))", "None", "Vector.empty"
        rows.append("    Case(" + json.dumps(c["name"]) + "," + json.dumps(c["policy"]) + f',{c["resolution"][0]},{c["resolution"][1]},' + ",".join([areas, fixes, exp, index, overlap]) + ")")
    return result + "  val cases: Vector[Case] = Vector(\n" + ",\n".join(rows) + "\n  )\n// format: on\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cases = json.loads(INPUT.read_text())["cases"]
    expected = [oracle(c) for c in cases]
    document = {"schema": 1, "input_sha256": hashlib.sha256(INPUT.read_bytes()).hexdigest(),
                "oracle": "exact integer microseconds and rational half-open rectangle membership; independent of eyes4s and eyesim",
                "results": [{"case": c["name"], **e} for c, e in zip(cases, expected, strict=True)]}
    for path, text in {OUTPUT: json.dumps(document, indent=2) + "\n", SCALA: scala(cases, expected)}.items():
        if args.check:
            assert path.read_text() == text, f"Fixture drift: {path}"
        else:
            path.write_text(text)
    print("Fixation AOI: exact membership, accounting, first entries, visits and transitions verified.")


if __name__ == "__main__":
    main()
