#!/usr/bin/env python3
"""Independent exact-predicate spatial return oracle; no R or native implementation."""
import argparse
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / "tools/r-parity/fixtures/cases/fixation-revisits.json"
OUTPUT = ROOT / "tools/r-parity/fixtures/fixation-revisits.json"
SCALA = ROOT / "compare/src/test/scala/eyes4s/compare/RevisitReference.scala"


def settings(c):
    return c.get("radius", 10), c.get("minimumLag", 2), c.get("maximumLag"), c.get("departure", True), c.get("distance", "euclidean")


def oracle(c):
    radius, minimum, maximum, departure, metric = settings(c)
    def magnitude(a, b):
        dx, dy = abs(Fraction(a[0]) - Fraction(b[0])), abs(Fraction(a[1]) - Fraction(b[1]))
        return dx + dy if metric == "manhattan" else dx * dx + dy * dy
    threshold = Fraction(radius) if metric == "manhattan" else Fraction(radius) ** 2
    def near(a, b):
        return magnitude(a, b) < threshold
    points, reference = c["points"], c.get("reference")
    rows = []
    for i, point in enumerate(points):
        eligible = [j for j in range(i) if i - j >= minimum and (maximum is None or i - j <= maximum)]
        opportunity = bool(eligible) and (not departure or not near(point, points[i - 1]))
        matches = [j for j in eligible if near(point, points[j])] if opportunity else []
        nearest = min(magnitude(point, points[j]) for j in eligible) if opportunity else None
        if nearest is not None:
            nearest = float(nearest) if metric == "manhattan" else math.sqrt(float(nearest))
        expected = None
        if opportunity and reference is not None:
            allowed = [r for r in reference if not departure or not near(r, points[i - 1])]
            denominator = sum(Fraction(r[2]) for r in allowed)
            numerator = sum(Fraction(r[2]) for r in allowed if any(near(r, points[j]) for j in eligible))
            if denominator:
                expected = float(numerator / denominator)
        rows.append({"opportunity": opportunity, "revisit": bool(matches), "lag": i - matches[-1] if matches else None,
                     "match_index": matches[-1] if matches else None, "distance": nearest, "expected": expected})
    opportunities = sum(r["opportunity"] for r in rows)
    revisits = sum(r["revisit"] for r in rows)
    expected = [r["expected"] for r in rows if r["opportunity"]]
    return {"rows": rows, "rate": revisits / opportunities if opportunities else None,
            "expected_revisits": sum(expected) if expected and all(e is not None for e in expected) else None}


def vector(values):
    return "Vector(" + ",".join(values) + ")"


def option(value, show=str):
    return "None" if value is None else "Some(" + show(value) + ")"


def scala(cases, results):
    header = (ROOT / "compare/src/main/scala/eyes4s/compare/FixationRevisits.scala").read_text().split("package ")[0]
    text = header + "package eyes4s.compare\n\n// Generated by tools/r-parity/generate_revisits.py. Do not hand-edit.\n// format: off\n"
    text += "private[compare] object RevisitReference:\n"
    text += "  final case class Row(opportunity: Boolean, revisit: Boolean, lag: Option[Int], matched: Option[Int], distance: Option[Double], expected: Option[Double])\n"
    text += "  final case class Case(name: String, points: Vector[(Double,Double)], radius: Double, minimum: Int, maximum: Option[Int], departure: Boolean, manhattan: Boolean, reference: Option[Vector[(Double,Double,Double)]], rows: Vector[Row], rate: Option[Double], expected: Option[Double])\n"
    records = []
    for c, result in zip(cases, results, strict=True):
        radius, minimum, maximum, departure, metric = settings(c)
        points = vector("(" + ",".join(repr(float(x)) for x in p) + ")" for p in c["points"])
        reference = option(c.get("reference"), lambda rs: vector("(" + ",".join(repr(float(x)) for x in r) + ")" for r in rs))
        rows = vector("Row(" + ",".join([str(r["opportunity"]).lower(), str(r["revisit"]).lower(), option(r["lag"]), option(r["match_index"]), option(r["distance"],repr), option(r["expected"],repr)]) + ")" for r in result["rows"])
        records.append("    Case(" + ",".join([json.dumps(c["name"]), points, repr(float(radius)), str(minimum), option(maximum), str(departure).lower(), str(metric == "manhattan").lower(), reference, rows, option(result["rate"],repr), option(result["expected_revisits"],repr)]) + ")")
    return text + "  val cases: Vector[Case] = Vector(\n" + ",\n".join(records) + "\n  )\n// format: on\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cases = json.loads(INPUT.read_text())["cases"]
    results = [oracle(c) for c in cases]
    output = {"schema": 1, "input_sha256": hashlib.sha256(INPUT.read_bytes()).hexdigest(),
              "oracle": "rational strict-distance predicates and weighted set unions; independent of eyesim and eyes4s",
              "results": [{"case": c["name"], **r} for c, r in zip(cases, results, strict=True)]}
    for path, text in {OUTPUT: json.dumps(output, indent=2) + "\n", SCALA: scala(cases, results)}.items():
        if args.check:
            assert path.read_text() == text, f"Fixture drift: {path}"
        else:
            path.write_text(text)
    print("Revisit exact predicates, lag selection, weighted conditional probabilities and complete denominators verified.")


if __name__ == "__main__":
    main()
