package eyes4s.laws

import eyes4s.codec.*
import eyes4s.kernel.*
import eyes4s.kernel.Unit2D.Px
import eyes4s.plan.*
import org.scalacheck.Gen

private[laws] object LocationComparisonCodecLawFixture:
  private def get[E, A](value: Either[E, A]): A = value.toOption.get

  private val frame = get(Frame.screen("location-comparison-codec-laws", 6, 4))

  /** A small valid plan whose seed changes bins, grid shape, observation
    * cardinalities, and the explicit query set. It is also the source for the
    * canonical pinned fixture generated by the registry owner.
    */
  def plan(seed: Long): LocationComparisonPlan =
    val phase   = Math.floorMod(seed, 6L).toInt
    val source  = get(LocationSourceId.of(s"location-codec-$phase.tsv"))
    val focal   = get(LocationTrialId.of("focal"))
    val matched = get(LocationTrialId.of("matched"))
    val control = get(LocationTrialId.of("control"))

    def point(x: Double, y: Double, ordinal: Long): LocationObservation =
      LocationObservation(source, ordinal, Pt[Px](x, y))
    def trial(id: LocationTrialId, rows: Vector[LocationObservation]): LocationTrial =
      get(LocationTrial.of(id, rows))
    def query(
        id: String,
        focal: LocationTrialId,
        matched: LocationTrialId,
        control: LocationTrialId
    ): LocationComparisonQuery =
      get(LocationComparisonQuery.of(id, focal, matched, control))

    val shift = phase.toDouble / 10.0
    val input = get(
      LocationInput.of(
        frame,
        Vector(
          trial(
            focal,
            Vector(point(0.2 + shift, 0.2, 1L), point(2.2, 0.2 + shift, 2L)) ++
              Option.when(phase % 2 == 0)(point(4.2, 2.2, 3L)).toVector
          ),
          trial(
            matched,
            Vector(point(0.2, 0.2 + shift, 4L), point(2.2 + shift, 0.2, 5L))
          ),
          trial(
            control,
            Vector(point(5.2 - shift, 3.2, 6L), point(5.2, 1.2 + shift, 7L))
          )
        )
      )
    )
    val queries = Vector(query("focal-comparison", focal, matched, control)) ++
      Option
        .when(phase % 3 == 0)(query("matched-comparison", matched, focal, control))
        .toVector
    get(LocationComparisonPlan.binned(input, 2 + phase % 2, 2 + phase % 3, queries))

  val plans: Gen[LocationComparisonPlan] =
    Gen.choose(0L, 1000L).map(plan)

class LocationComparisonCodecLawSuite extends munit.DisciplineSuite:
  import LocationComparisonCodecLawFixture.*

  private def samePlan(left: LocationComparisonPlan, right: LocationComparisonPlan): Boolean =
    left.inputHash == right.inputHash &&
      left.planHash == right.planHash &&
      left.grid.nx == right.grid.nx &&
      left.grid.ny == right.grid.ny &&
      left.input.trials.map(_.id) == right.input.trials.map(_.id) &&
      left.queries.map(q => (q.id, q.focal, q.matched, q.control)) ==
      right.queries.map(q => (q.id, q.focal, q.matched, q.control))

  private def sameResult(left: LocationComparisonRun, right: LocationComparisonRun): Boolean =
    samePlan(left.plan, right.plan) &&
      left.result.inputHash == right.result.inputHash &&
      left.result.planHash == right.result.planHash &&
      left.result.maps.map(map => map.trial -> map.result.map(_.bins)) ==
      right.result.maps.map(map => map.trial -> map.result.map(_.bins)) &&
      left.result.outcomes.map(outcome =>
        (
          outcome.query.id,
          outcome.matched.map(_.value),
          outcome.control.map(_.value),
          outcome.difference
        )
      ) == right.result.outcomes.map(outcome =>
        (
          outcome.query.id,
          outcome.matched.map(_.value),
          outcome.control.map(_.value),
          outcome.difference
        )
      )

  checkAll(
    "location comparison plan",
    CodecLaws.roundTrip(
      LocationComparisonPlanCodec.of(LocationComparisonDefinitions.plan),
      plans,
      samePlan
    )
  )
  checkAll(
    "location comparison result",
    CodecLaws.roundTrip(
      LocationComparisonResultCodec.codec,
      plans.map(plan => LocationComparisonRun(plan, plan.run)),
      sameResult
    )
  )

  checkAll(
    "location input",
    CodecLaws.roundTrip(
      LocationInputCodec.of(DefinitionId.of("test.location-input", 1).toOption.get),
      plans.map(_.input),
      (left: LocationInput, right: LocationInput) =>
        left.frame == right.frame && left.trials.map(t =>
          t.id -> t.observations
        ) == right.trials.map(t => t.id -> t.observations)
    )
  )
