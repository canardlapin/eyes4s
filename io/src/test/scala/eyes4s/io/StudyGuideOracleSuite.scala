/** Pinned StudyGuide outputs from before the X1 prepared-work extraction.
  *
  * Every literal below was printed by running this exact guide, fixture and
  * estimate list at commit 6218627 (the last commit before StudyPlan delegated
  * pairing to DirectedPairSchedule), then copied verbatim. Computed score columns use
  * the suite-wide 1e-12 oracle tolerance. Sigma uses exact canonical decimal spelling
  * (the historical integral .0 suffix is removed); every other column, including every
  * failure row, reason and selected/successful/failed/contributing denominator,
  * must match exactly.
  */
class StudyGuideOracleSuite extends munit.FunSuite:
  private val OracleTolerance               = 1e-12
  private def get[E, A](e: Either[E, A]): A = e.fold(error => fail(s"$error"), identity)
  private val header                        = Vector(
    "participant",
    "image",
    "phase",
    "fixation",
    "x_px",
    "y_px",
    "onset_us",
    "duration_us",
    "sample_count"
  )
  private val records = MatchedControlFixtures.fixations.map(r =>
    Vector(
      r.participant,
      r.image,
      r.phase,
      r.ordinal.toString,
      r.x.toString,
      r.y.toString,
      r.onsetMicros.toString,
      r.durationMicros.toString,
      r.sampleCount.toString
    )
  )
  private def csv(rows: Vector[Vector[String]]): String = Rfc4180.encode(header +: rows)

  private val pinnedColumns = Vector(
    "scope",
    "participant",
    "stimulus",
    "phase",
    "estimator",
    "sigma",
    "edges",
    "component",
    "matched",
    "control",
    "difference",
    "status",
    "reason",
    "matched_selected",
    "matched_successful",
    "matched_failed",
    "matched_contributing",
    "control_selected",
    "control_successful",
    "control_failed",
    "control_contributing"
  )
  private val numericColumns = Set("matched", "control", "difference")

  private def check(
      rows: Vector[Vector[String]],
      estimates: Vector[StudyEstimate[Px]],
      expected: Vector[Vector[String]],
      expectedFailures: Vector[String]
  ): Unit =
    assert(pinnedColumns.forall(ContrastCsv.header.contains))
    val output = get(StudyGuide.run(csv(rows), estimates))
    val table  = output.contrasts.rows.map(r => ContrastCsv.header.zip(r).toMap)
    assertEquals(table.size, expected.size)
    assertEquals(expectedFailures.size, expected.size)
    table.zip(expected).zip(expectedFailures).zipWithIndex.foreach {
      case (((row, pinned), failures), index) =>
        pinnedColumns.zip(pinned).foreach { case (column, value) =>
          val clue = s"row $index column $column"
          if numericColumns.contains(column) && value.nonEmpty then
            assertEqualsDouble(row(column).toDouble, value.toDouble, OracleTolerance, clue)
          else if column == "sigma" then
            assertEquals(row(column), value.stripSuffix(".0"), clue)
          else assertEquals(row(column), value, clue)
        }
        assertEquals(row("estimation_failures"), failures, s"row $index estimation_failures")
    }

  private val multiscale = Vector(
    StudyEstimate.Binned(),
    StudyEstimate.Gaussian(get(Sigma.px(0.5)), EdgePolicy.Truncate),
    StudyEstimate.Gaussian(get(Sigma.px(1.0)), EdgePolicy.Renormalise),
    StudyEstimate.Gaussian(get(Sigma.px(2.0)), EdgePolicy.Truncate)
  )
  private val practice = records.take(4).map(_.updated(2, "practice"))
  private val failing  = Vector(
    StudyEstimate.Binned(),
    StudyEstimate.Gaussian(get(Sigma.px(0.01)), EdgePolicy.Truncate)
  )

  private val pinnedBandwidthMessage =
    "A bandwidth of 0.01000 is smaller than a fifth of the 1.000 cell size, so the kernel " +
      "would fall inside a single cell and the estimate would be a histogram wearing a " +
      "smoother's name. Use a coarser grid or a wider bandwidth."
  private val pinnedBandwidthFailures = Vector(
    "StudyKey(s1,a,encode)",
    "StudyKey(s1,a,practice)",
    "StudyKey(s1,a,recall)",
    "StudyKey(s1,b,encode)",
    "StudyKey(s1,b,recall)",
    "StudyKey(s1,c,encode)",
    "StudyKey(s1,c,recall)",
    "StudyKey(s2,a,encode)",
    "StudyKey(s2,a,recall)",
    "StudyKey(s2,b,encode)",
    "StudyKey(s2,b,recall)",
    "StudyKey(s2,c,encode)",
    "StudyKey(s2,c,recall)"
  ).map(key => s"Trial $key: $pinnedBandwidthMessage").mkString(" | ")

  test("scalar binned StudyGuide output matches the pre-extraction pinned rows") {
    check(records, Vector(StudyEstimate.Binned()), pinnedScalar, Vector.fill(6)(""))
  }

  test("matched, control and difference cells use pinned cross-runtime decimal bytes") {
    val output = get(StudyGuide.run(csv(records), Vector(StudyEstimate.Binned())))
    val row    = ContrastCsv.header.zip(output.contrasts.rows.head).toMap
    assertEquals(
      Vector("matched", "control", "difference").map(row),
      Vector("1", "0.72", "0.28")
    )
  }

  test("multiscale StudyGuide output matches the pre-extraction pinned rows") {
    check(records, multiscale, pinnedMultiscale, Vector.fill(24)(""))
  }

  test("failure rows, excluded trials and denominators match the pre-extraction pinned rows") {
    check(
      records ++ practice,
      failing,
      pinnedFailures,
      Vector.fill(7)("") ++ Vector.fill(7)(pinnedBandwidthFailures)
    )
  }

